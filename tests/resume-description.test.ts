// Новая выгрузка hh: компания стоит между началом и концом периода,
// отраслей несколько, длительность сокращена до «мес».
const HH_NEW = `Опыт работы: 2 года 8 месяцев

Фев 2022 –
Тест Ритейл
Авг 2022
test.ru
7 мес
Розничная торговля
• Несетевая розница, мелкий опт
Товары народного потребления (непищевые)
• Табак (продвижение, оптовая торговля)
Менеджер по продажам
- Консультация покупателей и бизнес-
процессов магазина
Достижения:
- В топ-5 по городу

Июл 2025 –
Тест Тех
сейчас
Алматы test.kz
1 год 4 мес Информационные технологии, системная интеграция, интернет
• Системная интеграция, автоматизация технологических и бизнес-процессов предприятия,
ИТ-консалтинг
Бизнес-аналитик
- Описание интеграции с сайтом shop.kz`;

describe("Новая выгрузка hh", () => {
  const parsed = parseResume(HH_NEW);

  it("собирает период, разорванный названием компании", () => {
    expect(parsed.experience).toHaveLength(2);
    expect(parsed.experience[0].period).toBe("Фев 2022 – Авг 2022");
    expect(parsed.experience[0].companyName).toBe("Тест Ритейл");
    expect(parsed.experience[1].period).toBe("Июл 2025 – сейчас");
  });

  it("берёт должность после всех отраслей", () => {
    expect(parsed.experience[0].position).toBe("Менеджер по продажам");
    expect(parsed.experience[1].position).toBe("Бизнес-аналитик");
  });

  it("склеивает слово, разорванное переносом, и держит подзаголовки отдельно", () => {
    expect(parsed.experience[0].description?.split("\n")).toEqual([
      "Консультация покупателей и бизнес-процессов магазина",
      "Достижения:",
      "В топ-5 по городу",
    ]);
  });

  it("не выбрасывает обязанность с адресом сайта", () => {
    expect(parsed.experience[1].description).toBe(
      "Описание интеграции с сайтом shop.kz",
    );
  });
});

