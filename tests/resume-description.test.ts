import { describe, expect, it } from "vitest";
import { parseResume } from "@/lib/resume/parse";

// Описание обязанностей: раньше оно обрезалось и собирало мусор.
// Причины, которые здесь проверяются:
//   1. обязанности через «*» принимались за список отраслей и терялись;
//   2. строка, перенесённая PDF на следующую, выбрасывалась;
//   3. «Опыт вождения» открывал раздел опыта заново;
//   4. колонтитул страницы («Резюме обновлено …», «1/3») попадал внутрь.
// Данные вымышленные.

const HH_STARS = `Опыт работы — 6 лет

Март 2024 — АО Тестовое бюро
Июль 2026
Астана
2 года 5 месяцев
Ведущий инженер поддержки
* Сопровождение и техническое обслуживание IT-систем и персональных компьютеров
Национального банка Республики Казахстан.
* Техническая поддержка пользователей.
Иванов Иван • Резюме обновлено 22 сентября 2026 в 00:01
1/3

* Настройка рабочих мест.

Навыки
Настройка ПК

Опыт вождения
Имеется собственный автомобиль
Права категории B

История общения с кандидатом
Отклики`;

describe("Описание опыта: выгрузка hh со звёздочками", () => {
  const parsed = parseResume(HH_STARS);
  const job = parsed.experience[0];

  it("находит должность", () => {
    expect(job.position).toBe("Ведущий инженер поддержки");
  });

  it("склеивает пункт, перенесённый на две строки", () => {
    expect(job.description?.split("\n")[0]).toBe(
      "Сопровождение и техническое обслуживание IT-систем и персональных компьютеров Национального банка Республики Казахстан.",
    );
  });

  it("сохраняет все пункты, даже после разрыва страницы", () => {
    expect(job.description?.split("\n")).toHaveLength(3);
    expect(job.description).toContain("Настройка рабочих мест.");
  });

  it("не тащит колонтитулы и чужие разделы", () => {
    expect(job.description).not.toContain("Резюме обновлено");
    expect(job.description).not.toContain("1/3");
    expect(job.description).not.toContain("автомобиль");
    expect(job.description).not.toContain("История общения");
  });
});

