import { describe, expect, it } from "vitest";
import { parseResume } from "@/lib/resume/parse";

// Образование в выгрузках с hh. Образцы повторяют настоящие случаи,
// на которых разбор ошибался: имена и названия условные.

function education(body: string) {
  return parseResume(`Тестов Тест\n${body}`).education;
}

describe("Образование: новая выгрузка hh (год отдельной строкой)", () => {
  it("склеивает название вуза, перенесённое после инициала", () => {
    expect(
      education(`Образование
Высшее
2022
Павлодарский государственный университет имени С.
Высшее
Торайгырова, Павлодар
Энергетический, Коммуникации и коммуникационные технологии
2019
Павлодарский колледж транспорта и коммуникаций
Среднее
Автоматика, телемеханика и связь
специальное
Навыки
Excel`),
    ).toEqual([
      {
        institution:
          "Павлодарский государственный университет имени С. Торайгырова, Павлодар",
        specialty: "Энергетический, Коммуникации и коммуникационные технологии",
        years: "2022",
      },
      {
        institution: "Павлодарский колледж транспорта и коммуникаций",
        specialty: "Автоматика, телемеханика и связь",
        years: "2019",
      },
    ]);
  });

  it("склеивает перенос после запятой и не путает его с уровнем", () => {
    expect(
      education(`Образование
Неоконченное высшее
2022
Международный университет информационных технологий,
Неоконченное
Алматы
высшее
Факультет компьютерных технологий, Информационная безопасность
Навыки`),
    ).toEqual([
      {
        institution: "Международный университет информационных технологий, Алматы",
        specialty: "Факультет компьютерных технологий, Информационная безопасность",
        years: "2022",
      },
    ]);
  });

  it("склеивает перенос, когда вторая строка начинается с маленькой буквы", () => {
    expect(
      education(`Образование
Высшее
2021
Восточно-Казахстанский государственный технический
Высшее
университет имени Д. Серикбаева, Усть-Каменогорск
Информационные технологии и бизнес, Информационные системы
Навыки`)[0],
    ).toEqual({
      institution:
        "Восточно-Казахстанский государственный технический университет имени Д. Серикбаева, Усть-Каменогорск",
      specialty: "Информационные технологии и бизнес, Информационные системы",
      years: "2021",
    });
  });

  it("не считает колонтитул страницы учебным заведением", () => {
    expect(
      education(`Образование
Среднее специальное
2014
Тестов Тест • Резюме обновлено 14 сентября 2026 в 14:45
Среднее
Южно-Казахстанский университет имени
специальное
М. Ауэзова
Организация перевозок
Навыки`),
    ).toEqual([
      {
        institution: "Южно-Казахстанский университет имени М. Ауэзова",
        specialty: "Организация перевозок",
        years: "2014",
      },
    ]);
  });

  it("не приклеивает к вузу специальность с маленькой буквы", () => {
    expect(
      education(`Образование
Высшее
2013
Карагандинский экономический университет Казпотребсоюза,
Высшее
Караганда
юриспруденция, юрист
Навыки`)[0],
    ).toEqual({
      institution: "Карагандинский экономический университет Казпотребсоюза, Караганда",
      specialty: "юриспруденция, юрист",
      years: "2013",
    });
  });

  it("склеивает перенесённую специальность", () => {
    expect(
      education(`Образование
Высшее
2017
Государственный университет управления, Москва
Высшее
Кафедра управления природопользованием, Экология и
природопользование
Навыки`)[0].specialty,
    ).toBe("Кафедра управления природопользованием, Экология и природопользование");
  });

  it("английская выгрузка с колонтитулом перед годом", () => {
    expect(
      education(`Education
Higher
Тестов Тест • Resume updated 16 September 2026 at 14:49
2023
Евразийский национальный университет имени Л. Н. Гумилёва,
Higher
Нур-Султан
Факультет информационных технологий, Автоматизация и управление
Skills`),
    ).toEqual([
      {
        institution: "Евразийский национальный университет имени Л. Н. Гумилёва, Нур-Султан",
        specialty: "Факультет информационных технологий, Автоматизация и управление",
        years: "2023",
      },
    ]);
  });
});

describe("Образование: старая выгрузка hh (год в конце строки)", () => {
  it("берёт вуз из строки над специальностью", () => {
    expect(
      education(`Образование
Уровень
Высшее
Тестовый государственный университет имени М. О. Ауэзова, Шымкент
Информационные технологии, Радиотехника, бакалавр 2020
Знание языков
Казахский`),
    ).toEqual([
      {
        institution: "Тестовый государственный университет имени М. О. Ауэзова, Шымкент",
        specialty: "Информационные технологии, Радиотехника, бакалавр",
        years: "2020",
      },
    ]);
  });

  it("разбирает несколько учебных заведений подряд", () => {
    expect(
      education(`Образование
Уровень
Высшее
Тестовый университет имени Абая
Юриспруденция, Юриспруденция 2015
Колледж менеджмента и бизнеса города Астаны
Правоведение, Юриспруденция 2012
Знание языков`),
    ).toEqual([
      {
        institution: "Тестовый университет имени Абая",
        specialty: "Юриспруденция, Юриспруденция",
        years: "2015",
      },
      {
        institution: "Колледж менеджмента и бизнеса города Астаны",
        specialty: "Правоведение, Юриспруденция",
        years: "2012",
      },
    ]);
  });

  it("склеивает специальность, перенесённую перед годом", () => {
    expect(
      education(`Образование
Уровень
Высшее
Тестовый университет международных отношений, Алматы
Факультет менеджмента, Ресторанное дело и гостиничный бизнес,
бакалавр 2022
Знание языков`)[0],
    ).toEqual({
      institution: "Тестовый университет международных отношений, Алматы",
      specialty: "Факультет менеджмента, Ресторанное дело и гостиничный бизнес, бакалавр",
      years: "2022",
    });
  });

  it("убирает колонтитул и номер страницы после образования", () => {
    expect(
      education(`Образование
Уровень
Высшее
Тестовый университет систем управления, Томск
РТФ, Защита информации 2015
Тестов Тест Резюме обновлено 17 октября 2026 в 06:47
3/4
Знание языков`),
    ).toEqual([
      {
        institution: "Тестовый университет систем управления, Томск",
        specialty: "РТФ, Защита информации",
        years: "2015",
      },
    ]);
  });
});

describe("Образование: редкие переносы", () => {
  it("склеивает имя из двух слов после «имени»", () => {
    expect(
      education(`Образование
Высшее
2026
Российский университет дружбы народов имени Патриса
Высшее
Лумумбы, Москва
Организационный консалтинг
Навыки`)[0],
    ).toEqual({
      institution: "Российский университет дружбы народов имени Патриса Лумумбы, Москва",
      specialty: "Организационный консалтинг",
      years: "2026",
    });
  });

  it("не клеит специальность к короткому названию с маленькой буквы", () => {
    expect(
      education(`Образование
Среднее специальное
2019
еаги
Среднее
гостиничное дело, Менеджмент организации
специальное
Навыки`)[0],
    ).toEqual({
      institution: "еаги",
      specialty: "гостиничное дело, Менеджмент организации",
      years: "2019",
    });
  });

  it("старая выгрузка: год перенёсся под длинную специальность", () => {
    expect(
      education(`Образование
Уровень
Высшее
Тестовый государственный университет имени Коркыт Ата, Кызылорда
Информационные системы (бакалавр информационных систем), бакалавр
2025
Astana IT University
Computer Science 2023
Знание языков`),
    ).toEqual([
      {
        institution: "Тестовый государственный университет имени Коркыт Ата, Кызылорда",
        specialty: "Информационные системы (бакалавр информационных систем), бакалавр",
        years: "2025",
      },
      {
        institution: "Astana IT University",
        specialty: "Computer Science",
        years: "2023",
      },
    ]);
  });
});

describe("Образование без учебного заведения", () => {
  it("сохраняет уровень, если больше ничего не указано", () => {
    expect(
      education(`Образование
Уровень
Среднее образование
Навыки`),
    ).toEqual([{ institution: "Среднее образование", specialty: null, years: null }]);
  });

  it("не принимает колонтитул за учебное заведение", () => {
    expect(
      education(`Образование
Уровень
Среднее
Тестов Тест Резюме обновлено 17 сентября 2026 в 16:25
2/3
Знание языков`),
    ).toEqual([{ institution: "Среднее образование", specialty: null, years: null }]);
  });

  it("не путает курсы и тесты с образованием", () => {
    expect(
      education(`Образование
Бакалавр
2023
Тестовый технический университет, Алматы
Бакалавр
Бизнес-школа, Менеджмент
Тесты, экзамены
2024
IELTS
British Council, 7.0`),
    ).toEqual([
      {
        institution: "Тестовый технический университет, Алматы",
        specialty: "Бизнес-школа, Менеджмент",
        years: "2023",
      },
    ]);
  });
});
