import { describe, expect, it } from "vitest";
import { parseResume } from "@/lib/resume/parse";

// Языки в резюме пишут по-разному. Разборщик не должен превращать
// уровень владения в отдельный «язык» и не должен выдавать повторы:
// на странице кандидата список языков рисуется по значениям,
// и два одинаковых значения ломали отрисовку.

function languagesOf(block: string): string[] {
  return parseResume(`Иванов Иван Иванович\n\n${block}`).languages;
}

describe("Языки из резюме", () => {
  it("уровень через запятую не становится отдельным языком", () => {
    const languages = languagesOf(
      "Языки\nКазахский, разговорный уровень\nАнглийский, разговорный уровень",
    );

    expect(languages).toEqual([
      "Казахский — разговорный уровень",
      "Английский — разговорный уровень",
    ]);
  });

  it("повторов не остаётся даже при разном регистре", () => {
    const languages = languagesOf("Языки\nРусский, РУССКИЙ, русский");
    expect(languages).toEqual(["Русский"]);
  });

  it("запись через тире не разрывается", () => {
    const languages = languagesOf(
      "Знание языков\nРусский — Родной\nАнглийский — B1",
    );
    expect(languages).toEqual(["Русский — Родной", "Английский — B1"]);
  });

  it("уровень без языка перед ним отбрасывается", () => {
    expect(languagesOf("Языки\nсвободное владение, Немецкий")).toEqual([
      "Немецкий",
    ]);
  });

  it("второй уровень не приписывается тому же языку", () => {
    const languages = languagesOf("Языки\nАнглийский, B2, разговорный");
    expect(languages).toEqual(["Английский — B2"]);
  });
});
