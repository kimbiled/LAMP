import "server-only";

// Адрес, по которому система доступна снаружи.
//
// Ссылки «Поделиться» собираются из него. Пока система запущена только
// на вашем компьютере, здесь пусто — тогда адрес берётся из браузера
// (получится http://localhost:3000, он работает только на этом компьютере).
//
// Когда систему опубликуем в интернете, достаточно будет прописать
// в файле .env строку вида APP_URL=https://lamp.example.kz — и все
// ссылки сразу станут правильными, включая уже созданные.

export function publicBaseUrl(): string | null {
  const value = (process.env.APP_URL ?? "").trim();
  if (!value) return null;

  // Лишняя косая черта в конце сломала бы адрес: два слэша подряд.
  return value.endsWith("/") ? value.slice(0, -1) : value;
}
