"use client";

import { useEffect, useRef } from "react";
import { usePathname } from "next/navigation";

// Отметка «в этой вкладке мы уже ходили по системе».
//
// Нужна кнопке «Назад». Само по себе число страниц в истории браузера
// ничего не говорит: вкладка могла открыться пустой, и шаг назад увёл бы
// на белый экран. А вот если внутри системы был хотя бы один переход,
// значит назад точно есть куда идти.
//
// Хранится в sessionStorage: это память одной вкладки, при закрытии
// она исчезает, и в новой вкладке отсчёт начинается заново.

export const NAV_MEMORY_KEY = "lamp-navigated";

export function NavMemory() {
  const pathname = usePathname();

  // Адрес, с которого началась эта загрузка страницы. Сравниваем с ним,
  // а не считаем «первый вызов»: в режиме разработки React запускает
  // эффекты дважды, и счётчик срабатывал бы вхолостую.
  const startedAt = useRef(pathname);

  useEffect(() => {
    // Пока адрес тот же, переходов не было: на эту страницу могли
    // попасть по прямой ссылке, и возвращаться некуда.
    if (pathname === startedAt.current) {
      return;
    }

    try {
      sessionStorage.setItem(NAV_MEMORY_KEY, "1");
    } catch {
      // Приватный режим может запрещать запись. Тогда кнопка «Назад»
      // просто уведёт в список — это тоже рабочее поведение.
    }
  }, [pathname]);

  return null;
}
